        T.best      = [0.553 0.725 0.980];   % 蓝（最优曲线）
        T.cmap      = [0.255 0.827 0.725;    % 工件配色（连续渐变青->橙）
                       0.349 0.780 0.588;
                       0.463 0.733 0.451;
